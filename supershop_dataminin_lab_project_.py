# Prepare data for anomaly detection
anomaly_features = rfm[['Recency', 'Frequency', 'Monetary']].copy()

# Scale features
scaler = StandardScaler()
anomaly_scaled = scaler.fit_transform(anomaly_features)

print("✅ Data prepared for anomaly detection")
print(f"📊 Shape: {anomaly_scaled.shape}")

# 1. Isolation Forest
print("⏳ Running Isolation Forest...")

iso_forest = IsolationForest(contamination=0.05, random_state=42, n_estimators=100)
rfm['Anomaly_IF'] = iso_forest.fit_predict(anomaly_scaled)
rfm['Anomaly_IF'] = rfm['Anomaly_IF'].map({1: 0, -1: 1})  # 0 = Normal, 1 = Anomaly

n_anomalies_if = rfm['Anomaly_IF'].sum()
print(f"✅ Isolation Forest - Anomalies detected: {n_anomalies_if} ({n_anomalies_if/len(rfm)*100:.2f}%)")

# 2. Local Outlier Factor (LOF)
print("⏳ Running Local Outlier Factor...")

lof = LocalOutlierFactor(n_neighbors=20, contamination=0.05)
rfm['Anomaly_LOF'] = lof.fit_predict(anomaly_scaled)
rfm['Anomaly_LOF'] = rfm['Anomaly_LOF'].map({1: 0, -1: 1})

n_anomalies_lof = rfm['Anomaly_LOF'].sum()
print(f"✅ LOF - Anomalies detected: {n_anomalies_lof} ({n_anomalies_lof/len(rfm)*100:.2f}%)")

# 3. One-Class SVM
print("⏳ Running One-Class SVM...")

# Sample if too large (One-Class SVM is slow)
if len(anomaly_scaled) > 5000:
    print("   (Using sample for faster processing)")
    sample_idx = np.random.choice(len(anomaly_scaled), 5000, replace=False)
    oc_svm = OneClassSVM(nu=0.05, kernel='rbf', gamma='auto')
    oc_svm.fit(anomaly_scaled[sample_idx])
    rfm['Anomaly_SVM'] = oc_svm.predict(anomaly_scaled)
else:
    oc_svm = OneClassSVM(nu=0.05, kernel='rbf', gamma='auto')
    rfm['Anomaly_SVM'] = oc_svm.fit_predict(anomaly_scaled)

rfm['Anomaly_SVM'] = rfm['Anomaly_SVM'].map({1: 0, -1: 1})

n_anomalies_svm = rfm['Anomaly_SVM'].sum()
print(f"✅ One-Class SVM - Anomalies detected: {n_anomalies_svm} ({n_anomalies_svm/len(rfm)*100:.2f}%)")

# Combined Anomaly Score (majority voting)
rfm['Anomaly_Combined'] = ((rfm['Anomaly_IF'] + rfm['Anomaly_LOF'] + rfm['Anomaly_SVM']) >= 2).astype(int)

